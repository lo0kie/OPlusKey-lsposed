package com.lookie.opluskey.ui.screen.combo

import androidx.compose.ui.unit.Dp

/**
 * 组合行标题里那几样宽度 —— **整列量一次**，五行十行都用同一份。
 *
 *  为什么不能每行各量各的：列的宽一旦逐行浮动，分隔符就会跟着前一个名字的长短走，
 *  一列下来每行都错开（[ComboKeyChip] 那几格之所以定宽就是为了防这件事）。
 *
 *  **按位置而不是按「第几颗键」**：第 [columns] 的第 i 项是「所有组里位置 i 那一枚框」的宽度。
 *  两列的组与三列的组因此共用前两列 —— 第 3 枚框只会出现在三颗那一档的行上，前两枚照样与
 *  别的行竖着对齐。
 *
 *  为什么连分隔符的宽度也一起带上：居中要算「这一块占多宽」，而 `×` 两边各 6dp 的内边距
 *  是画在 `Text` 上的，`Row` 自己不知道。把它算进预算里，块宽才准，居中的左右两段才真的相等。
 */
internal class ComboTitleWidths(
    /** 每一列（第 i 个键名，**不带方括号**）的宽度 —— 整列里最长的那个。 */
    val columns: List<Dp>,
    /** 分隔符那一格的总宽（`×` 的宽度 + 两侧内边距）。 */
    val separator: Dp,
)
