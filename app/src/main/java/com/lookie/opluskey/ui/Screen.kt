package com.lookie.opluskey.ui

import io.github.suqi8.coui.kmp.nav.core.NavKey

/**
 * 页面（系统设置 → 快捷键 → 按键绑定 → 自定义命令 / 条件执行 → 「打开应用」/「更多选项」）。
 * 路标交给 coui-nav 的返回栈（`NavDisplay` + `navBackStackOf`，见 [SettingsPage.navStack]），
 * 谁在谁上面由栈说了算（「打开应用」两个来路的返回目标天然正确）。
 * key 不需要 `@Serializable`：栈是纯内存栈、不做状态保存 —— 页面进程死了本来也不该恢复。
 */
internal enum class Screen : NavKey {
    SHORTCUTS,
    BINDING,
    COMMANDS,

    /**
     * 「条件执行」—— 从「按键绑定」页顶栏 ⋮ 菜单进来（**唯一入口**）。
     *
     *  它单独一页而不是「自定义命令」页的第三个页签：它编的东西与单条 / 多条不是一回事 ——
     *  后者写命令正文，这里只挑**已有命令**；一张表单塞三档，每档都得解释「为什么只有这一块能用」。
     *
     *  它有自己的草稿（`branchDraft`）：分叉不是命令库的一条记录，落盘与字段都与命令正文不同。
     *  与「自定义命令」页仅共用「底部保存」那一套交互，不共用状态。
     */
    BRANCHES,

    /**
     * 「打开应用」——挑本机应用
     *
     *  它**有两个入口**：「按键绑定」页的入口格（挑中的应用绑给**当前手势**）、
     * 「自定义命令」页里「添加命令」浮层的「选择应用」（挑中的应用作为**一步**）。
     * 父级 = 压它下面的那一页，不需要额外记账。
     */
    APP_PICKER,

    /**
     * 「选择界面」——一个应用里挑**具体哪个 Activity**。
     *
     *  **唯一入口**：「选择应用」页上**点**某一行（那一页没有「选中」这个中间态，点一行就是进这一页）。
     *  父级是「选择应用」页 —— 返回先回那一页；在那里点确认只记草稿（`onDraftPicked`），
     *  真正落盘要再按上一级那颗 FAB。
     */
    ACTIVITY_PICKER,

    /**
     * 「更多选项」——从首页「其他 → 更多选项」那一行进来（**唯一入口**，⋮ 里那一项已删）。
     *
     * 版本、仓库地址那几行从首页搬到了这里；运行状态与配置导入导出也都在这一页。
     */
    ABOUT,

    /**
     * 「捐赠列表」——从首页「其他 → 捐赠打赏」那层菜单的最后一项进来（唯一入口）。
     *
     *  它跟那三个收款码去处**不是一类**（那边是「怎么给」、这边是「谢谢谁」），
     *  所以菜单里用一条**加深分隔**把它们分成两组，这一项单独在第二组。
     */
    DONATE_LIST,

    /**
     * 「通用设置」——从首页「其他」卡第一行进来（**唯一入口**，在「更多选项」上面）。
     *
     *  装着两节：**接口选择**（ColorOS 专属接口 / AOSP 标准接口）与**按键行为**
     *  （振动反馈与强度、执行时提示）。两者都是**全局**项，与「这颗键绑了什么」无关，
     *  所以不放在「按键绑定」那一页。
     */
    GENERAL,
}
