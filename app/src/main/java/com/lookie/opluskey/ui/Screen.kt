package com.lookie.opluskey.ui

import io.github.suqi8.coui.kmp.nav.core.NavKey

/**
 * 页面（系统设置 → 快捷键 → 按键绑定 → 自定义命令 / 条件执行 → 「打开应用」/「更多选项」）。
 * 路标交给 coui-nav 的返回栈（`NavDisplay` + `navBackStackOf`，见 [SettingsPage.navStack]），
 * 谁在谁上面由栈说了算（「打开应用」两个来路的返回目标天然正确）。
 * key 不需要 `@Serializable`：栈是纯内存栈、不做状态保存 —— 页面进程死了本来也不该恢复。
 */
internal enum class Screen : NavKey {
    SHORTCUTS,
    BINDING,

    /**
     * 「独立设置」—— **这一档**（一颗键 / 一组组合）对公共项的覆盖，从它们各自页面顶栏
     * 那颗设置键进来（两个入口、同一个页面）。
     *
     *  装的是：使用 ColorOS 接口、振动反馈（含强度）、执行时提示与文案；改的是一组组合时
     *  另加「无操作时执行按键命令」与「按键之间的等待」。看哪一档由 `SettingsTargetState` 记
     *  （界面状态，不落盘）。
     *
     *  与 [GENERAL] 分工：那一页是**公共**那份（默认值），与本页冲突时本页优先 ——
     *  这一档自己设过的永远盖过公共设置。
     */
    KEY_SETTINGS,
    COMMANDS,

    /**
     * 「条件执行」—— 从「按键绑定」页顶栏 ⋮ 菜单进来（**唯一入口**）。
     *
     *  它单独一页而不是「自定义命令」页的第三个页签：它编的东西与单条 / 多条不是一回事 ——
     *  后者写命令正文，这里只挑**已有命令**；一张表单塞三档，每档都得解释「为什么只有这一块能用」。
     *
     *  它有自己的草稿（`branchDraft`）：分叉不是命令库的一条记录，落盘与字段都与命令正文不同。
     *  与「自定义命令」页仅共用「底部保存」那一套交互，不共用状态。
     */
    BRANCHES,

    /**
     * 「场景动作」—— 点「系统场景」页里某一块的**某一行动作**进来，只编那一块的那一档。
     *
     *  它不是场景表本身（那是 [BRANCHES]），而是那张表里一格的内容：三档手势各一屏动作网格
     *  （组合键的场景块只有短按 / 长按两档），与「按键绑定」页长得一样，**没有按键设置**
     *  （那些卡调的是这颗键怎么判，场景块没有自己的判据可调）。
     *
     *  在编哪一块由 `sceneBindingAt` 记（界面状态、不落盘）—— 与 [COMBO_EDIT] 同一个做法，
     *  参数走枚举带不进去。写的是**草稿**（`BranchDraft`），落盘仍归 [BRANCHES] 那颗确认。
     */
    SCENE_BINDING,

    /**
     * 「打开应用」——挑本机应用
     *
     *  它**有两个入口**：「按键绑定」页的入口格（挑中的应用绑给**当前手势**）、
     * 「自定义命令」页里「添加命令」浮层的「选择应用」（挑中的应用作为**一步**）。
     * 父级 = 压它下面的那一页，不需要额外记账。
     */
    APP_PICKER,

    /**
     * 「选择界面」——一个应用里挑**具体哪个 Activity**。
     *
     *  **唯一入口**：「选择应用」页上**点**某一行（那一页没有「选中」这个中间态，点一行就是进这一页）。
     *  父级是「选择应用」页 —— 返回先回那一页；在那里点确认只记草稿（`onDraftPicked`），
     *  真正落盘要再按上一级那颗 FAB。
     */
    ACTIVITY_PICKER,

    /**
     * 「更多选项」——从首页「其他 → 更多选项」那一行进来（**唯一入口**，⋮ 里那一项已删）。
     *
     * 版本、仓库地址那几行从首页搬到了这里；运行状态与配置导入导出也都在这一页。
     */
    ABOUT,

    /**
     * 「捐赠列表」——从首页「其他 → 捐赠打赏」那层菜单的最后一项进来（唯一入口）。
     *
     *  它跟那三个收款码去处**不是一类**（那边是「怎么给」、这边是「谢谢谁」），
     *  所以菜单里用一条**加深分隔**把它们分成两组，这一项单独在第二组。
     */
    DONATE_LIST,

    /**
     * 「公共设置」——从首页「按键操作」卡第二行与「按键功能」页顶栏那颗齿轮进来。
     *
     *  装着三节：**接口选择**（ColorOS 专属接口 / AOSP 标准接口）、**按键行为**
     *  （振动反馈与强度、执行时提示）与**组合按键设置**。都是**公共**项，与「这颗键绑了什么」
     *  无关 —— 每颗键自己的那一份在 [KEY_SETTINGS] 里，那是**按键级**，优先于这里。
     */
    GENERAL,

    /**
     * 「按键功能」页 —— **按键列表 + 组合按键列表**收在同一页（从首页「按键操作」卡里那一行进来，
     * 唯一入口）。
     *
     *  两个清单本来是两处：按键列表在首页，组合按键列表自己一页。它们回答的是同一件事
     *  （这台机器上有哪些「按键」可以配），拆成两处反而要在首页摆一列清单占掉半屏 ——
     *  所以并成一页，首页只留「按键操作」那张卡（组合按键 / 添加按键两行）。
     *
     *  组合键那部分不在「按键绑定」页那三个手势 tab 里：那三个 tab 是「某颗键的一档手势」，
     *  而组合键是**两颗键一起按**——一张表、每档两格（短按 / 长按），与手势三档不是一回事。
     */
    KEYS,

    /**
     * 「组合键」的某一档 —— 从列表点某一行进来（**唯一入口**）。
     *
     *  在看哪一档由 `ComboEditState.editingId` 记（界面状态、不落盘）：栈里这一页只有一个位置，
     *  参数走 `Screen` 枚举带不进去。
     */
    COMBO_EDIT,

    /**
     * 「自定义变量」列表 —— 管清单的那一页（新建 / 删除 / 改值）。
     *
     *  两个入口都进去：首页「其他」卡里那一行，以及绑定页变量那格弹出的抽屉**右上角那颗 +**
     *  （那一格本身是「挑一步操作绑上去」，不是进页 —— 见 `ActionCatalog.VARS_TILE`）。
     *
     *  它单独一页而不是塞进「按键设置」：变量是**一份清单**（可能好几十条），要点进去改值、
     *  要能新建；做成设置页里的几行，长起来就没有地方放了。
     *
     *  这一页只读写 `opluskey_vars.conf`（见 `VariableStore`），与主配置无关 ——
     *  所以它不参与配置广播，也不受主开关那一层闸门管。
     */
    VARIABLES,
}
